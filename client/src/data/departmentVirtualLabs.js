/**
 * Returns all Virtual Labs mapped for a given employee ID or department ID.
 * Defaults gracefully to 'demo-employee-01' (MoSPI).
 */
export function getDepartmentVirtualLabs(employeeIdOrDeptId) {
  if (!employeeIdOrDeptId) return DEPARTMENT_VIRTUAL_LABS['demo-employee-01'] || [];

  if (DEPARTMENT_VIRTUAL_LABS[employeeIdOrDeptId]) {
    return DEPARTMENT_VIRTUAL_LABS[employeeIdOrDeptId];
  }

  // Lookup by departmentId or fuzzy match
  for (const [key, labs] of Object.entries(DEPARTMENT_VIRTUAL_LABS)) {
    if (labs.some(l => l.departmentId === employeeIdOrDeptId || l.department?.toLowerCase().includes(String(employeeIdOrDeptId).toLowerCase()))) {
      return labs;
    }
  }

  return DEPARTMENT_VIRTUAL_LABS['demo-employee-01'] || [];
}

/**
 * Finds a specific virtual lab by ID across all departments and fallback pools.
 */
export function getVirtualLabById(labId) {
  if (!labId) return null;
  for (const labs of Object.values(DEPARTMENT_VIRTUAL_LABS)) {
    const found = labs.find(l => l.id === labId);
    if (found) return found;
  }
  return null;
}

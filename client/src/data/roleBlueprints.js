// Configurable Proficiency Level Thresholds
export const PROFICIENCY_LEVELS = [
  { min: 0, max: 39, label: 'Novice', category: 'critical', badgeClass: 'bg-gov-red text-white' },
  { min: 40, max: 59, label: 'Developing', category: 'developing', badgeClass: 'bg-gov-amber text-white' },
  { min: 60, max: 74, label: 'Proficient', category: 'developing', badgeClass: 'bg-blue-600 text-white' },
  { min: 75, max: 89, label: 'Advanced', category: 'strong', badgeClass: 'bg-gov-green text-white' },
  { min: 90, max: 100, label: 'Expert', category: 'strong', badgeClass: 'bg-emerald-700 text-white' },
];

export function getProficiencyLevel(score) {
  const rounded = Math.round(score);
  return PROFICIENCY_LEVELS.find(lvl => rounded >= lvl.min && rounded <= lvl.max) || PROFICIENCY_LEVELS[1];
}
